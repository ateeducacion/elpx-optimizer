export type MessageKey = keyof typeof es;
const DICTS: Record<Lang, Record<MessageKey, string>> = { es, en };

/** Picks the initial language from the browser, defaulting to Spanish. */
export function detectLang(languages: readonly string[]): Lang {
  for (const l of languages) {
    if (l.toLowerCase().startsWith('es')) return 'es';
    if (l.toLowerCase().startsWith('en')) return 'en';
  }
  return 'es';
}

/** Translates a key, filling {placeholders}. Unknown keys return the key. */
export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const template = (DICTS[lang] as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
